from typing import TypedDict, Annotated, List, Dict, Any, Union
import operator
from langgraph.graph import StateGraph, END
from langchain_core.messages import BaseMessage, HumanMessage, AIMessage
from backend.app.core.config import settings
from backend.app.services.curriculum_manager import CurriculumManager

class LearningState(TypedDict):
    # Core session data
    session_id: str
    user_id: str
    current_concept: str
    level: int

    # Research and Teaching
    research_package: Dict[str, Any]
    teaching_content: str
    thinking_prompt: str
    practical_task: str

    # Evidence and Evaluation
    learner_responses: Annotated[List[Dict[str, Any]], operator.add]
    quiz_metrics: Dict[str, Any]
    evaluation: Dict[str, Any]

    # The Decision
    next_action: str # 'ADVANCE', 'REMEDIATE', 'RETEST', 'COMPLETE'
    attempt_number: int

class ClarioGraph:
    def __init__(self, db_session):
        self.db = db_session
        self.workflow = self._build_graph()

    def _build_graph(self):
        builder = StateGraph(LearningState)

        # Define Nodes
        builder.add_node("nova_research", self.node_nova)
        builder.add_node("mira_teach", self.node_mira)
        builder.add_node("ayan_probe", self.node_ayan)
        builder.add_node("kira_apply", self.node_kira)
        builder.add_node("zayn_assess", self.node_zayn)
        builder.add_node("elara_eval", self.node_elara)
        builder.add_node("clario_decision", self.node_decision)

        # Define Edges
        builder.set_entry_point("nova_research")
        builder.add_edge("nova_research", "mira_teach")
        builder.add_edge("mira_teach", "ayan_probe")
        builder.add_edge("ayan_probe", "kira_apply")
        builder.add_edge("kira_apply", "zayn_assess")
        builder.add_edge("zayn_assess", "elara_eval")
        builder.add_edge("elara_eval", "clario_decision")

        # Conditional Routing from Decision
        builder.add_conditional_edges(
            "clario_decision",
            self.route_decision,
            {
                "REMEDIATE": "mira_teach",
                "RETEST": "zayn_assess",
                "ADVANCE": END,
                "COMPLETE": END
            }
        )

        return builder.compile()

    # --- Node Implementations ---
    # These wrap the existing agent logic into LangGraph nodes

    def node_nova(self, state: LearningState):
        # Wraps Nova Research Logic
        # In a full impl, this would call run_nova_research
        return {"research_package": {"status": "validated", "sources": []}}

    def node_mira(self, state: LearningState):
        # Wraps MiraTeachingAgent
        return {"teaching_content": "Lesson content generated by Mira"}

    def node_ayan(self, state: LearningState):
        # Wraps AyanCriticalThinkingAgent
        return {"thinking_prompt": "Reasoning challenge generated by Ayan"}

    def node_kira(self, state: LearningState):
        # Wraps KiraPracticalAgent
        return {"practical_task": "Real-world task generated by Kira"}

    def node_zayn(self, state: LearningState):
        # Wraps ZaynQuizAgent
        return {"quiz_metrics": {"score": 85, "correct": 4, "total": 5}}

    def node_elara(self, state: LearningState):
        # Wraps ElaraEvaluationAgent
        return {"evaluation": {"mastery": "strong", "confidence": 0.85}}

    def node_decision(self, state: LearningState):
        # Uses the AdaptivePolicy logic to decide next move
        eval_data = state.get("evaluation", {})
        if eval_data.get("mastery") == "strong":
            return {"next_action": "ADVANCE"}
        return {"next_action": "REMEDIATE"}

    def route_decision(self, state: LearningState):
        return state["next_action"]

    async def run(self, initial_state: LearningState):
        return await self.workflow.ainvoke(initial_state)
